"""Generate the procedure index and per-button source views from the canonical BSL."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
lines = (ROOT/'src/Module.bsl').read_text().splitlines()
routines = {}
for i, line in enumerate(lines):
    start = re.match(r'\s*(Функция|Процедура)\s+(\w+)\(',line,re.I)
    if start:
        name = start[2]
        end = next(j for j in range(i+1,len(lines)) if re.match(r'^\s*Конец(?:Функции|Процедуры)\b',lines[j],re.I))
        routines[name] = (i+1,end+1)
buttons = {
'ТестНастроекНажатие': ('connection','Тест настроек','Создаёт настройки выбранного узла и проверяет соединение. Успешный ответ проверяет доступ к API, но ещё не проверяет запись цен, остатков или свойств.'),
'ВыгрузитьКаталогНажатие': ('catalog','Выгрузить каталог','Принимает список штрихкодов или явное подтверждение полной выгрузки. Синхронизирует kit_id_1c по свойству характеристики в 1С для вариантов основного каталога. Формирует отбор, передаёт категории и варианты, для основного сайта запускает цены. В пробном режиме сверяет категории и пишет результаты проверки ID.'),
'ВыгрузитьКатегорииНажатие': ('categories','Выгрузить категории','В диалоге «Да» означает сверку с записью файла. «Нет» запускает сбор категорий по товарам с остатком, создание недостающих категорий, корректировку родителей и сверку.'),
'ОбновитьЦеныНажатие': ('prices','Обновить цены','Запускает ценовую выборку для выбранного узла. Для основного сайта в расчёте участвует склад скидок 218. Отправка цен и обновление характеристики скидки — отдельные операции.'),
'ОбновитьОстаткиНажатие': ('stocks','Обновить остатки','Вызывает полный режим. Для основного сайта собирает девять складов, вычитает резерв и передаёт сумму на 106. Затем проверяет кандидатов на обнуление.'),
'ТоварПоСкладамНажатие': ('split-stock','Товар по складам','Для введённых штрихкодов сравнивает доступное количество отдельно по каждому из девяти складов. Требует однозначного варианта, рассчитывает разницу, запрашивает подтверждение, отправляет пакет и повторно читает остатки.'),
'ПолучитьКитИДНажатие': ('variant-id','Получить KIT ID','Принимает один или несколько ШК. Пустой ввод выбирает все ШК КИТ. После общего подтверждения при вводе ШК выполняет отдельный поиск по каждому коду и проверяет точное совпадение barcode. При пустом вводе читает каталог постранично, проверяет однозначность ID и затем ищет характеристику в 1С. Каждая запись выполняется в отдельной транзакции. Проверяет прежнее имя и новое значение до фиксации транзакции.'),
'ЗагрузитьЗаказыНажатие': ('orders','Загрузить заказы','Показывает предупреждение Garage Sale и читает страницы заказов. Для подходящих новых заказов вызывает заполнение заказа покупателя. Путь может записывать и проводить документы, создавать заявки и файлы для печати.')}
calls={}
for n,(a,b) in routines.items():
    body='\n'.join(lines[a:b-1])
    body=re.sub(r'"(?:[^"]|"")*"|//[^\n]*',' ',body)
    calls[n]=sorted(set(re.findall(r'(?<![.\w])(\w+)\s*\(',body)) & routines.keys())
def link(n,prefix):
    a,b=routines[n]
    return f'[{n}]({prefix}src/Module.bsl#L{a}-L{b})'
idx=['# Указатель процедур и функций','',f'{len(routines)} определений в порядке исходника. Ссылки открывают полное тело. Вызовы выделены статически по имени внутри модуля. Методы платформы и вызываемые по строке команды сюда не входят.','', '| Определение | Прямые вызовы внутри модуля |','|---|---|']
for n in routines:
    idx.append('| '+link(n,'../')+' | '+(', '.join(link(t,'../') for t in calls[n]) or '—')+' |')
(ROOT/'docs/INDEX.md').write_text('\n'.join(idx)+'\n')
folder=ROOT/'docs/buttons';folder.mkdir(exist_ok=True)
for n,(slug,label,description) in buttons.items():
    a,b=routines[n]
    done=set()
    pending=[n]
    while pending:
        k=pending.pop()
        if k in done:continue
        done.add(k);pending.extend(calls[k])
    content=[f'# {label}','',description,'',link(n,'../../'),'','## Код обработчика','','```bsl',*lines[a-1:b],'```','','## Подпрограммы','', 'Статически достижимые вызовы, включая условные ветви. Каждая ссылка ведёт к реализации.','']
    content.extend('- '+link(t,'../../') for t in routines if t in done and t!=n)
    (folder/(slug+'.md')).write_text('\n'.join(content)+'\n')
print(len(routines),len(buttons),len(lines))
